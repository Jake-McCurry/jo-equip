export type ResourceFormat = "book" | "playlist" | "app" | "pdf" | "video";

export type ChannelId = "church" | "growth" | "evidence";

export interface SubTopicItem {
  number: number;
  title: string;
  /** ID of a book in src/data/books.ts — when set, this item's PDF button links to that book. */
  bookId?: string;
  /** ID of a YouTube video inside this sub-topic's `playlistId` — when set, this item's Video button deep-links to that video. */
  videoId?: string;
  /**
   * ID of the playlist (in src/data/playlists.ts) that contains `videoId`, when
   * that video lives in a DIFFERENT playlist than the sub-topic's own
   * `playlistId`. Defaults to the sub-topic's `playlistId` when omitted.
   */
  videoPlaylistId?: string;
  /**
   * ID of an article body in a per-subtopic article data file (e.g. src/data/bcgArticles.ts).
   * When set, the item's title becomes a link to /channels/<channelId>/<subId>/<articleId>
   * which renders the full long-form article. Items without an articleId are list-only.
   */
  articleId?: string;
  /**
   * When true, the item is NOT rendered in the sub-topic's visible list and is
   * omitted from the ItemList JSON-LD, but its `articleId` still generates a
   * long-form article page. Use for supporting articles that should only be
   * reachable via inline links from other articles.
   */
  unlisted?: boolean;
  /**
   * Optional section label. When consecutive items share a section, the
   * sub-topic list page renders a subheading above the first item of each
   * section (e.g. "Core Principles" / "Kingdom Impact").
   */
  section?: string;
  /** Optional per-item external link overrides. */
  links?: {
    pdf?: string;
    video?: string;
    app?: string;
  };
}

export interface SubTopic {
  id: string;
  channelId: ChannelId;
  name: string;
  description?: string;
  formats?: ResourceFormat[];
  items?: SubTopicItem[];
  /** Link to the JO App series page if available */
  appUrl?: string;
  /** ID of a playlist in src/data/playlists.ts — required for any item.videoId to resolve to a /playlist deep-link. */
  playlistId?: string;
  /** ID of a book in src/data/books.ts — when set, the sub-topic page shows the book cover and a topic-level Book button. */
  bookId?: string;
  /** ID of a cover image in src/assets/books/covers/ — shows the cover without requiring a downloadable book. Falls back to bookId for the cover lookup. */
  coverId?: string;
  /** When true, the list page renders items without the leading "1. 2. 3." number badges. */
  hideNumbers?: boolean;
  /** When set, this sub-topic is a child of another sub-topic. Children are hidden
   *  from the channel index grid; their parent's detail page lists them as cards.
   *  Direct child URLs still work so previously-published links don't 404. */
  parentId?: string;
}

export interface Channel {
  id: ChannelId;
  name: string;
  shortName: string;
  tagline: string;
  description: string;
  accentColor: string;
  gradient: string;
}

